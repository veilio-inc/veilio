// Spec 064: build packages/engine/src/words.ts - the common English words the
// engine leaves readable - from SCOWL (http://wordlist.aspell.net/), sizes 10,
// 20 and 35 of english-words and american-words: lower-case, alphabetic, three
// letters or more. Rare words (skerry, vellum, tarn) are beyond size 35 and stay
// masked: they identify a codebase more than they describe it.
//
//   node scripts/build-word-list.mjs <path to an unpacked scowl-2020.12.07>
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = process.argv[2]
if (!root) throw new Error('usage: build-word-list.mjs <scowl dir>')
const words = new Set()
for (const kind of ['english-words', 'american-words'])
  for (const size of ['10', '20', '35'])
    for (const w of new TextDecoder('latin1').decode(readFileSync(join(root, 'final', `${kind}.${size}`))).split('\n'))
      if (/^[a-z]{3,}$/.test(w)) words.add(w)
const sorted = [...words].sort()
const out = `// Generated by scripts/build-word-list.mjs from SCOWL 2020.12.07, sizes 10-35
// (english-words, american-words). Do not edit by hand. Licence: words.NOTICE.
// ${sorted.length} words.
export const ENGLISH_WORDS = ${JSON.stringify(sorted.join(' '))}
`
writeFileSync('packages/engine/src/words.ts', out)
writeFileSync('packages/engine/src/words.NOTICE', readFileSync(join(root, 'Copyright')))
console.log(`${sorted.length} words, ${out.length} bytes`)
